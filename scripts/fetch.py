"""Fetch the Chromium version pinned in config/upstream.json (CORE-001, issue #62).

The checkout is created with depot_tools:

  1. shallow-clone chromium/src at the pinned tag into <checkout>/src
  2. write <checkout>/.gclient with an unmanaged "src" solution
  3. gclient sync --nohooks --no-history (dependencies from src/DEPS)
  4. gclient runhooks (toolchains, sysroots, generated files)
  5. verify the checked-out commit and record it in <checkout>/.brumel/fetch.json

By default the script only PRINTS this plan. Nothing is downloaded unless you
pass --execute. A full fetch downloads many gigabytes and takes a long time.

Status: written in Phase 1 before the first real fetch; the exact depot_tools
flags are validated by the build spike (issue #61).
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import pprint
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from brumeltools import (  # noqa: E402
    IS_WINDOWS,
    Step,
    ToolError,
    UpstreamPin,
    free_gigabytes,
    git,
    load_pin,
    main_wrapper,
    print_plan,
    require_tools,
    run_plan,
    toolchain_env,
)

# Planning assumption from docs/development/BUILDING.md, not a measurement.
DEFAULT_MIN_FREE_GB = 100
# Long checkout paths break parts of the Windows toolchain; keep it short.
WINDOWS_MAX_CHECKOUT_PATH = 40
STATE_DIR = ".brumel"
STATE_FILE = "fetch.json"


def gclient_file(pin: UpstreamPin, target_os: list[str]) -> str:
    """Contents of the .gclient file for an unmanaged, pinned checkout."""
    solution = {
        "name": "src",
        "url": pin.repository,
        # Unmanaged: gclient never moves src; the pinned tag is checked out by us.
        "managed": False,
        "custom_deps": {},
        "custom_vars": {},
    }
    lines = [
        "# Generated by brumel scripts/fetch.py. Do not edit; re-run the script instead.",
        f"# Chromium {pin.version}",
        "solutions = " + pprint.pformat([solution], sort_dicts=False),
    ]
    if target_os:
        lines.append(f"target_os = {sorted(set(target_os))!r}")
    return "\n".join(lines) + "\n"


def preflight(checkout: Path, pin: UpstreamPin, min_free_gb: float) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) about the machine and the checkout location."""
    errors: list[str] = []
    warnings: list[str] = []

    missing = require_tools(["git", "gclient"])
    if missing:
        errors.append(
            "missing tools on PATH: " + ", ".join(missing)
            + " (install depot_tools: see docs/development/BUILDING.md)"
        )

    resolved = str(checkout.resolve())
    if " " in resolved:
        errors.append(f"checkout path must not contain spaces: {resolved}")
    if IS_WINDOWS:
        if len(resolved) > WINDOWS_MAX_CHECKOUT_PATH:
            warnings.append(
                f"checkout path is {len(resolved)} characters; keep it under "
                f"{WINDOWS_MAX_CHECKOUT_PATH} (for example C:\\src\\brumel)"
            )
        if not _windows_long_paths_enabled():
            warnings.append("Windows long-path support (LongPathsEnabled) appears to be off")

    free = free_gigabytes(checkout)
    if free < min_free_gb:
        errors.append(
            f"only {free:.0f} GB free at {resolved}; at least {min_free_gb:.0f} GB required "
            "(override with --min-free-gb if you know what you are doing)"
        )

    src = checkout / "src"
    if src.exists():
        if not (src / ".git").exists():
            errors.append(f"{src} exists but is not a Git checkout; choose an empty directory")
        else:
            head_tag = _describe_tag(src)
            if head_tag != pin.version:
                errors.append(
                    f"{src} is at {head_tag or 'an unknown commit'}, not the pinned {pin.version}; "
                    "use a new checkout directory for a different version"
                )
    return errors, warnings


def build_plan(
    checkout: Path, pin: UpstreamPin, jobs: int, target_os: list[str]
) -> list[Step]:
    src = checkout / "src"
    env = toolchain_env()
    state_dir = checkout / STATE_DIR
    steps: list[Step] = [
        Step("Create the checkout directory", action=lambda: checkout.mkdir(parents=True, exist_ok=True)),
    ]
    if not (src / ".git").exists():
        steps.append(Step(
            f"Shallow-clone chromium/src at tag {pin.version}",
            argv=[
                "git", "-c", "core.autocrlf=false", "-c", "core.filemode=false",
                "clone", "--depth", "1", "--branch", pin.version,
                pin.repository, "src",
            ],
            cwd=checkout,
        ))
    steps += [
        Step("Write .gclient (unmanaged src solution)",
             action=lambda: (checkout / ".gclient").write_text(
                 gclient_file(pin, target_os), encoding="utf-8", newline="\n")),
        Step("Create the state directory", action=lambda: state_dir.mkdir(exist_ok=True)),
        Step(
            "Sync dependencies listed in src/DEPS (no history, no hooks yet)",
            argv=[
                "gclient", "sync", "--nohooks", "--no-history", "--shallow",
                "--jobs", str(jobs), "--output-json", str(state_dir / "gclient-sync.json"),
            ],
            cwd=checkout,
            env=env,
        ),
        Step("Run hooks (toolchains, sysroots, generated files)",
             argv=["gclient", "runhooks", "--jobs", str(jobs)], cwd=checkout, env=env),
        Step("Verify the checked-out commit and record it",
             action=lambda: record_state(checkout, pin)),
    ]
    return steps


def record_state(checkout: Path, pin: UpstreamPin) -> dict:
    src = checkout / "src"
    revision = git(["rev-parse", "HEAD"], src).strip()
    tree = git(["rev-parse", "HEAD^{tree}"], src).strip()
    if pin.revision and revision != pin.revision:
        raise ToolError(
            f"src is at {revision}, but config/upstream.json pins revision {pin.revision}. "
            "The tag may have moved upstream: stop and investigate before building."
        )
    state = {
        "chromium_version": pin.version,
        "revision": revision,
        "src_tree": tree,
        "ungoogled_tag": pin.ungoogled_tag,
        "fetched_at": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat(),
        "gclient_sync_summary": f"{STATE_DIR}/gclient-sync.json",
    }
    state_path = checkout / STATE_DIR / STATE_FILE
    state_path.parent.mkdir(exist_ok=True)
    state_path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Recorded {state_path}: src {revision} (tree {tree})")
    if not pin.revision:
        print(
            "Note: config/upstream.json has no chromium.revision yet. After the first verified "
            f'fetch, set "revision": "{revision}" in a reviewed pull request.'
        )
    return state


def _describe_tag(src: Path) -> str | None:
    try:
        return git(["describe", "--tags", "--exact-match", "HEAD"], src, check=False).strip() or None
    except OSError:
        return None


def _windows_long_paths_enabled() -> bool:
    try:
        import winreg

        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SYSTEM\CurrentControlSet\Control\FileSystem") as key:
            value, _ = winreg.QueryValueEx(key, "LongPathsEnabled")
            return value == 1
    except OSError:
        return False


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--checkout", required=True, type=Path,
                        help="directory that will contain .gclient and src/ (outside this repository)")
    parser.add_argument("--execute", action="store_true", help="actually download; without it only the plan is printed")
    parser.add_argument("--jobs", type=int, default=max(1, min(os.cpu_count() or 4, 16)),
                        help="parallel gclient jobs (default: CPU count, max 16)")
    parser.add_argument("--target-os", action="append", default=[], metavar="OS",
                        help="extra target_os for .gclient, e.g. win or linux (repeatable)")
    parser.add_argument("--min-free-gb", type=float, default=DEFAULT_MIN_FREE_GB,
                        help=f"minimum free disk space required (default {DEFAULT_MIN_FREE_GB})")
    parser.add_argument("--config", type=Path, default=None, help="alternative upstream.json (for testing)")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    pin = load_pin(args.config) if args.config else load_pin()
    checkout: Path = args.checkout

    repo_root = Path(__file__).resolve().parents[1]
    if repo_root == checkout.resolve() or repo_root in checkout.resolve().parents:
        raise ToolError("the checkout must live outside the Brumel repository (Chromium source is never committed)")

    errors, warnings = preflight(checkout, pin, args.min_free_gb)
    for warning in warnings:
        print(f"warning: {warning}")
    steps = build_plan(checkout, pin, args.jobs, args.target_os)
    print_plan(f"Fetch Chromium {pin.version} into {checkout}", steps, args.execute)
    if not args.execute:
        print("\n.gclient that would be written:\n" + gclient_file(pin, args.target_os))
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 2
    if args.execute:
        run_plan(steps)
        print("\nFetch complete.")
    return 0


if __name__ == "__main__":
    sys.exit(main_wrapper(main))
